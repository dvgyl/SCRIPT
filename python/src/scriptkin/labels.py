"""Questionnaire labels: one score or refusal for each scale of each block.

The scoring rules come from `contract/instruments.json` (generated by `scriptkin.instruments`).
A block with too many missing items gives a refusal, never a score of zero. Items outside the
scoring rule, such as `difficulty`, never enter a score. Safety flags are counted for audit only.
"""

from __future__ import annotations

import csv
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from scriptkin import instruments
from scriptkin.quality import Refusal, RefusalCode
from scriptkin.recording import BlockOutcome, QuestionnaireBlock, Recording


@dataclass(frozen=True)
class Scale:
    """One scored sum. Up to `max_missing` skipped items are allowed, and are prorated when `prorate`."""

    name: str
    items: tuple[str, ...]
    max_missing: int
    multiplier: int = 1
    prorate: bool = False


@dataclass(frozen=True)
class Label:
    participant: str
    session: str
    instrument: str
    version: str
    locale: str
    administration: str
    block: int
    block_time: float
    boot: str
    outcome: BlockOutcome
    scale: str
    score: float | Refusal


def scales(rule: dict[str, Any]) -> tuple[Scale, ...]:
    """Parse one scoring rule of contract/instruments.json."""
    prorate = rule.get("missing") == "proRate"
    if rule["kind"] == "sum":
        return (Scale("total", tuple(rule["items"]), rule["maxMissing"], 1, prorate),)
    if rule["kind"] == "subscales":
        return tuple(
            Scale(name, tuple(items), rule["maxMissingPerScale"], rule["multiplier"], prorate)
            for name, items in rule["scales"].items()
        )
    raise ValueError(f"Unknown scoring rule kind {rule['kind']!r}.")


def score(scale: Scale, answers: dict[str, int | None], options: dict[str, set[int]]) -> float | Refusal:
    """Score one scale from the last answer to each item. A skipped or absent item is missing."""
    values = [answers.get(item) for item in scale.items]
    invalid = [
        item for item, v in zip(scale.items, values, strict=True) if v is not None and v not in options[item]
    ]
    if invalid:
        return Refusal(RefusalCode.UNDEFINED, f"Values outside the response options: {', '.join(invalid)}.")
    answered = [v for v in values if v is not None]
    missing = len(values) - len(answered)
    if missing > scale.max_missing:
        return Refusal(
            RefusalCode.TOO_FEW_VALUES,
            f"{missing} of {len(values)} items missing; the rule allows {scale.max_missing}.",
        )
    total = float(sum(answered))
    if missing and scale.prorate:
        total *= len(values) / len(answered)
    return scale.multiplier * total


def _block_labels(recording: Recording, block: QuestionnaireBlock, administration: str) -> list[Label]:
    ref = block.instrument

    def label(scale: str, value: float | Refusal) -> Label:
        return Label(
            recording.participant,
            recording.session_id,
            ref.id,
            ref.version,
            ref.locale,
            administration,
            block.block,
            block.started,
            block.boot,
            block.outcome,
            scale,
            value,
        )

    try:
        spec = instruments.instrument(ref.id)
    except KeyError:
        return [label("total", Refusal(RefusalCode.UNDEFINED, f"No scoring rule for {ref.id!r}."))]
    if spec["version"] != ref.version:
        detail = f"No scoring rule for {ref.id!r} version {ref.version!r}."
        return [label(s.name, Refusal(RefusalCode.UNDEFINED, detail)) for s in scales(spec["scoring"])]
    answers = {r.item: r.value for r in block.responses}
    options = {item["id"]: {o["value"] for o in item["options"]} for item in spec["items"]}
    return [label(s.name, score(s, answers, options)) for s in scales(spec["scoring"])]


def labels(recording: Recording) -> tuple[Label, ...]:
    """Score every questionnaire block of a recording, in block order."""
    administration = recording.context.administration if recording.context else "unknown"
    return tuple(
        label
        for block in recording.questionnaires
        for label in _block_labels(recording, block, administration)
    )


def safety_flag_count(recording: Recording) -> int:
    """The number of safety flags in the session, for audit. It is never a label."""
    return sum(len(block.flagged_items) for block in recording.questionnaires)


_CSV_COLUMNS = (
    "participant",
    "session",
    "instrument",
    "version",
    "locale",
    "administration",
    "block",
    "block_time",
    "boot",
    "outcome",
    "scale",
    "score",
    "refusal",
    "detail",
)


def write_labels_csv(labels: Iterable[Label], path: str | Path) -> None:
    """Write one row per label. A refused score has an empty `score` and a refusal code."""
    with Path(path).open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(_CSV_COLUMNS)
        for label in labels:
            score = label.score
            writer.writerow(
                (
                    label.participant,
                    label.session,
                    label.instrument,
                    label.version,
                    label.locale,
                    label.administration,
                    label.block,
                    label.block_time,
                    label.boot,
                    label.outcome,
                    label.scale,
                    "" if isinstance(score, Refusal) else score,
                    score.code if isinstance(score, Refusal) else "",
                    score.detail if isinstance(score, Refusal) else "",
                )
            )


def read_labels_csv(path: str | Path) -> tuple[Label, ...]:
    """Read labels that `write_labels_csv` wrote. Invalid input raises ValueError."""
    source = Path(path)
    result: list[Label] = []
    with source.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != _CSV_COLUMNS:
            raise ValueError(f"{source.name} does not have the label columns.")
        for line, row in enumerate(reader, start=2):
            try:
                score: float | Refusal = (
                    Refusal(RefusalCode(row["refusal"]), row["detail"])
                    if row["refusal"]
                    else float(row["score"])
                )
                result.append(
                    Label(
                        row["participant"],
                        row["session"],
                        row["instrument"],
                        row["version"],
                        row["locale"],
                        row["administration"],
                        int(row["block"]),
                        float(row["block_time"]),
                        row["boot"],
                        BlockOutcome(row["outcome"]),
                        row["scale"],
                        score,
                    )
                )
            except ValueError as e:
                raise ValueError(f"{source.name}, line {line}: {e}") from e
    return tuple(result)
